import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import subsetFont from 'subset-font';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const lucideRoot = path.join(projectRoot, 'node_modules', 'lucide-static');

const iconMap = {
  search: 'search',
  edit: 'pencil',
  camera: 'camera',
  upload: 'upload',
  close: 'x',
  back: 'chevron-left',
  forward: 'chevron-right',
  heart: 'heart',
  comment: 'message-circle',
  share: 'share-2',
  bookmark: 'bookmark',
  bell: 'bell',
  settings: 'settings',
  logout: 'log-out',
  location: 'map-pin',
  calendar: 'calendar',
  mail: 'mail',
  phone: 'phone',
  crown: 'crown',
  image: 'image',
  inbox: 'inbox',
  user: 'user',
  home: 'home',
  sparkles: 'sparkles',
  plus: 'plus',
  check: 'check',
  refresh: 'refresh-cw',
  trash: 'trash-2',
  eye: 'eye',
  gift: 'gift',
  shield: 'shield',
  help: 'help-circle',
  arrowUp: 'arrow-up',
  menu: 'menu',
  more: 'more-horizontal',
  file: 'file-text',
};

const codepoints = JSON.parse(
  await readFile(path.join(lucideRoot, 'font', 'codepoints.json'), 'utf8'),
);
const fontBuffer = await readFile(path.join(lucideRoot, 'font', 'lucide.ttf'));

const selectedCodepoints = Object.values(iconMap).map((lucideName) => {
  const codepoint = codepoints[lucideName];
  if (!codepoint) {
    throw new Error(`Lucide icon not found: ${lucideName}`);
  }
  return codepoint;
});

const text = selectedCodepoints.map((codepoint) => String.fromCodePoint(codepoint)).join('');
const subsetBuffer = await subsetFont(fontBuffer, text, {
  targetFormat: 'sfnt',
  noHinting: true,
  dropTables: ['DSIG'],
});

const base64Font = subsetBuffer.toString('base64');
const iconEntries = Object.entries(iconMap)
  .map(([name, lucideName]) => {
    const codepoint = codepoints[lucideName];
    const escaped = `\\u${codepoint.toString(16).toUpperCase().padStart(4, '0')}`;
    return `  ${name}: '${escaped}',`;
  })
  .join('\n');

const styles = `/* Generated by scripts/generate-icons.mjs. Do not edit manually. */
@font-face {
  font-family: 'AvinIcons';
  src: url('data:font/ttf;base64,${base64Font}') format('truetype');
  font-style: normal;
  font-weight: normal;
  font-display: block;
}

.app-icon {
  display: inline-flex;
  align-items: center;
  justify-content: center;
  font-family: 'AvinIcons';
  font-style: normal;
  font-weight: normal;
  line-height: 1;
  speak: none;
}
`;

const constants = `/* Generated by scripts/generate-icons.mjs. Do not edit manually. */
export const APP_ICONS = {
${iconEntries}
} as const;

export type AppIconName = keyof typeof APP_ICONS;
`;

await mkdir(path.join(projectRoot, 'src', 'styles'), { recursive: true });
await mkdir(path.join(projectRoot, 'src', 'constants'), { recursive: true });
await writeFile(path.join(projectRoot, 'src', 'styles', 'iconfont.scss'), styles, 'utf8');
await writeFile(path.join(projectRoot, 'src', 'constants', 'icons.ts'), constants, 'utf8');

process.stdout.write(
  `Generated ${Object.keys(iconMap).length} icons: ${(subsetBuffer.length / 1024).toFixed(1)} KB TTF`,
);
